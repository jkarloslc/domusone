-- ── Tabla 1: Programa semanal base (catálogo derivado del Excel) ──────────────
CREATE TABLE IF NOT EXISTS golf.riego_programa (
  id           UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  hoyo         SMALLINT,                        -- 1-18, NULL=rebombeo
  area         TEXT        NOT NULL,            -- Pista/Fairway, Taludes Green, Green, Salidas/Tees, Rebombeo Lago 5
  dia_semana   TEXT        NOT NULL,            -- Lunes..Domingo
  tipo_riego   TEXT        NOT NULL,            -- Manual/Manguera, Cañon Agricola
  origen       TEXT        NOT NULL,            -- Lago 2, Lago 7, Ordeña, Lago 12
  zona         TEXT,                            -- Sur, Norte
  hora_inicio  TEXT,
  hora_fin     TEXT,
  horas_prog   NUMERIC(6,2),
  m3_prog      NUMERIC(10,2),
  litros_prog  INTEGER,
  activo       BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── Tabla 2: Ejecución semanal (registro de cumplimiento por semana) ──────────
CREATE TABLE IF NOT EXISTS golf.riego_ejecucion (
  id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  id_programa_fk  UUID        NOT NULL REFERENCES golf.riego_programa(id) ON DELETE CASCADE,
  fecha_prog      DATE        NOT NULL,          -- Fecha real de la actividad
  semana_iso      SMALLINT    NOT NULL,          -- Semana ISO 1-53
  anio            SMALLINT    NOT NULL,
  status          TEXT        NOT NULL DEFAULT 'pendiente'
                  CHECK (status IN ('pendiente','completado','parcial','no_realizado')),
  hora_inicio_real TEXT,
  hora_fin_real    TEXT,
  horas_real       NUMERIC(6,2),
  m3_real          NUMERIC(10,2),
  observaciones    TEXT,
  id_usuario_fk    UUID        REFERENCES auth.users(id),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id_programa_fk, fecha_prog)
);

-- ── Tabla 3: Consumo diario real por origen de agua ───────────────────────────
CREATE TABLE IF NOT EXISTS golf.riego_consumo_diario (
  id               UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  fecha            DATE        NOT NULL,
  origen           TEXT        NOT NULL          -- Lago 7, Lago 2, Ordeña, Lago 12
                   CHECK (origen IN ('Lago 7','Lago 2','Ordeña','Lago 12')),
  m3_programado    NUMERIC(10,2),               -- Referencia del programa
  horas_bomba      NUMERIC(6,2),
  lectura_inicio   NUMERIC(12,2),               -- Caudalímetro inicio
  lectura_fin      NUMERIC(12,2),               -- Caudalímetro fin
  m3_real          NUMERIC(10,2),               -- lectura_fin - lectura_inicio (o manual)
  observaciones    TEXT,
  id_usuario_fk    UUID        REFERENCES auth.users(id),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (fecha, origen)
);

-- ── Índices ───────────────────────────────────────────────────────────────────
CREATE INDEX IF NOT EXISTS idx_riego_prog_dia   ON golf.riego_programa (dia_semana);
CREATE INDEX IF NOT EXISTS idx_riego_prog_area  ON golf.riego_programa (area);
CREATE INDEX IF NOT EXISTS idx_riego_ej_fecha   ON golf.riego_ejecucion (fecha_prog);
CREATE INDEX IF NOT EXISTS idx_riego_ej_semana  ON golf.riego_ejecucion (anio, semana_iso);
CREATE INDEX IF NOT EXISTS idx_riego_consumo_f  ON golf.riego_consumo_diario (fecha);

-- ── RLS ───────────────────────────────────────────────────────────────────────
ALTER TABLE golf.riego_programa       ENABLE ROW LEVEL SECURITY;
ALTER TABLE golf.riego_ejecucion      ENABLE ROW LEVEL SECURITY;
ALTER TABLE golf.riego_consumo_diario ENABLE ROW LEVEL SECURITY;

CREATE POLICY "allow_all_riego_programa"       ON golf.riego_programa       FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "allow_all_riego_ejecucion"      ON golf.riego_ejecucion      FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "allow_all_riego_consumo_diario" ON golf.riego_consumo_diario FOR ALL USING (true) WITH CHECK (true);

-- ── Grants ────────────────────────────────────────────────────────────────────
GRANT ALL ON golf.riego_programa, golf.riego_ejecucion, golf.riego_consumo_diario
  TO authenticated, anon, service_role;


